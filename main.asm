[org 0x8000] ;load all code in this file, into memory, on from 0x8000

jmp start ;  THIS CODE WILL BE AT 0x8000, JUMPED TO BY ENTRY POINT

gdt_start:
    ; 1. The Null Descriptor (8 bytes of 0)
    dd 0x0
    dd 0x0

    ; 2. The Code Segment
    ; Base=0, Limit=0xFFFFF, Flags=0x9A (Execute/Read), Granularity=0xCF (4KB blocks)
    dw 0xffff    ; Limit (bits 0-15)
    dw 0x0       ; Base (bits 0-15)
    db 0x0       ; Base (bits 16-23)
    db 10011010b ; Access byte
    db 11001111b ; Flags + Limit (bits 16-19)
    db 0x0       ; Base (bits 24-31)

    ; 3. The Data Segment
    ; Identical to Code, but Access=0x92 (Read/Write)
    dw 0xffff
    dw 0x0
    db 0x0
    db 10010010b ; Access byte
    db 11001111b
    db 0x0
gdt_end:

; This is the actual "gdt_descriptor"
gdt_descriptor:
    dw gdt_end - gdt_start - 1 ; Size of the GDT (16-bit)
    dd gdt_start               ; Address of the GDT (32-bit)
	
start:
    cli             ; 1. KILL INTERRUPTS. This is non-negotiable for PM switch.
    
    xor ax, ax      ; 2. Ensure DS is 0 so the GDT address is absolute
    mov ds, ax
    mov es, ax      ; ES was used for VRAM, but we need it for STOSB below

    ; --- Video Mode Code ---
    mov ax, 0x0013 
    int 0x10 

    ; --- Screen Clear Code ---
    mov ax, 0xA000  
    mov es, ax      
    xor di, di      
    mov al, 2       
    mov cx, 64000   
    rep stosb       

    ; --- Switch to Protected Mode ---
    lgdt [gdt_descriptor] 
    
    mov eax, cr0
    or eax, 1        
    mov cr0, eax
    
    jmp 0x08:start_32 ; The "Far Jump" to flush the pipeline

[bits 32]
%define backBuffer 0x20000  ; back buffer, directly edited

%define frontBuffer 0xA0000  ; actual vram that the screen displays. backBuffer
;                             data is copied directly to here in order to update
;                             the screen

%define playerData 0x30000  ; dd player.x dd player.y
start_32:
	mov ax, 0x10
	mov ds, ax 
	mov ss, ax
	mov es, ax
	
	
	mov ebp, 0x90000   ; Set the Base of the stack
	mov esp, ebp       ; Set the Top (current pointer) to the same spot
	
	mov dword [playerData], 10
	mov dword [playerData+4], 2

mainLoop:
	
	call check_retrace ;check if monitor is "retracing",
	test al, 1			;tests if true. if true, result = 1 (checks bit 1)
	
	jnz .run ; if test is true (result is 1), runs the rendering sequence
	; if test is false, test again
	call blastBuffer
	jmp mainLoop ; 
	
.run:
	call poll_key  ; gets keyboard input code (if any)
	cmp al, 0
	jz .skip_key_cases
	call key_cases
.skip_key_cases:
	
	call clearScreen ; fills back buffer with a color
	
	mov ecx, 8
	mov edx, 8
	call drawPixel ; drawPixel(ecx, edx)  sets color of a pixel at coordinates
	
	
	mov ecx, [playerData]
	mov edx, [playerData+4]
	call drawPlayer ; draws a 2x2 square at (ecx,edx) assuming (0, 0) is center of the screen
	jmp mainLoop ; go back to mainLoop 
	


blastBuffer: ; draws backBuffer onto main vram buffer
	mov esi, backBuffer  ; source address
	mov edi, frontBuffer ; destination adress
	mov ecx, 16000       ; number of doublewords to copy
	
	cld
	
	rep movsd
	ret
	
drawPixel:
	push edx
	imul edx, 320
	mov ebx, edx
	add ebx, ecx
	mov byte [backBuffer + ebx], 15
	pop edx
	ret
	
drawPlayer:  ;   drawPlayer( player.x ECX,  player.y EDX ) 
	call .screenX
	call .screenY
	
	cmp eax, 0
	jl .offScreen
	
	cmp ebx, 0
	jl .offScreen
	
	cmp eax, 319
	jg .offScreen
	
	;cmp ebx, 199
	;jge .offScreen
	
	; if on screen:
	
	imul ebx, 320
	add eax, ebx
	
	mov byte [backBuffer + eax], 15
	add eax, 1
	mov byte [backBuffer + eax], 15
	add eax, 319
	mov byte [backBuffer + eax], 15
	add eax, 1
	mov byte [backBuffer + eax], 15
	ret
	
.screenX:  ;     puts screen x coordinate into eax
	mov eax, ecx
	add eax, 160
	ret
.screenY:  ;     puts screen y coordinate into ebx
	mov ebx, edx
	add ebx, 100
	ret
.offScreen:
	ret
	

clearScreen:
	mov edi, backBuffer
	mov ecx, 16000
	
	mov eax, 0x02020202
	
	cld
	
	rep stosd
	ret

check_retrace:
	mov dx, 0x03DA
	in al, dx
	test al, 8 ; Check bit 3
	jnz .retrace_true
	mov ax, 0
	ret
.retrace_true:
	mov ax, 1
	ret
	

poll_key:
	in al, 0x64  ; key status port
	test al, 1
	jz .no_key
	in al, 0x60
	ret
.no_key:
	xor al, al
	ret
	

key_cases:

	cmp al, 0x11 ; test for W make code
	jnz .skipMakeW_key_cases
	call key_W_press
.skipMakeW_key_cases:

	cmp al, 0x1F ; test for S make code
	jnz .skipMakeS_key_cases
	call key_S_press
.skipMakeS_key_cases:

	cmp al, 0x1E ; test for A make code
	jnz .skipMakeA_key_cases
	call key_A_press
.skipMakeA_key_cases:

	cmp al, 0x20 ; test for D make code
	jnz .skipMakeD_key_cases
	call key_D_press
.skipMakeD_key_cases:
	ret

key_W_press:
	mov ebx, [playerData+4]
	sub ebx, 5
	mov [playerData+4], ebx
	ret
key_S_press:
	mov ebx, [playerData+4]
	add ebx, 5
	mov [playerData+4], ebx
	ret
key_A_press:
	mov ebx, [playerData]
	sub ebx, 5
	mov [playerData], ebx
	ret
key_D_press:
	mov ebx, [playerData]
	add ebx, 5
	mov [playerData], ebx
	ret


